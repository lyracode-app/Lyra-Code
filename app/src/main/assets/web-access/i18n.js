const translationTables = Object.fromEntries(['en','zh-TW'].map((language,i) => [language,Object.fromEntries(webTranslations.map(row => [row[0],row[i+1]]))]));
let interfaceLanguage = 'en';
function t(value, values={}) {
  const text=String(value ?? ''), match=text.match(/^(\s*)([\s\S]*?)(\s*)$/);
  const translated=match[1]+(translationTables[interfaceLanguage]?.[match[2]] ?? match[2])+match[3];
  return translated.replace(/\{(\w+)\}/g,(placeholder,key) => Object.hasOwn(values,key) ? String(values[key]) : placeholder);
}
function localizeStatic(root=document) {
  for (const node of root.querySelectorAll('[data-i18n]')) node.textContent=t(node.dataset.i18n);
  for (const attribute of ['title','placeholder','aria-label']) {
    for (const node of root.querySelectorAll(`[data-i18n-${attribute}]`)) node.setAttribute(attribute,t(node.getAttribute(`data-i18n-${attribute}`)));
  }
  document.documentElement.lang=interfaceLanguage;
  document.title=`Lyra Code · ${t('网页访问')}`;
}
function setInterfaceLocale(locale) {
  const next=['zh-CN','zh-TW','en'].includes(locale?.language) ? locale.language : 'en';
  const changed=next!==interfaceLanguage;interfaceLanguage=next;if(changed)localizeStatic();return changed;
}
